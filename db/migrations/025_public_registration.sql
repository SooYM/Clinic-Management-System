ALTER TABLE branches ADD COLUMN public_registration_enabled BOOLEAN NOT NULL DEFAULT FALSE, ADD COLUMN public_registration_version INT NOT NULL DEFAULT 1 CHECK(public_registration_version>0);
CREATE TABLE pending_registrations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  tenant_id BIGINT UNSIGNED NOT NULL,
  branch_id BIGINT UNSIGNED NOT NULL,
  reference VARCHAR(24) NOT NULL UNIQUE,
  submission_key CHAR(36) NOT NULL,
  request_hash CHAR(64) NOT NULL,
  receipt_token_hash CHAR(64) NOT NULL UNIQUE,
  ticket_number VARCHAR(20) NOT NULL,
  service_date DATE NOT NULL,
  payload JSON NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','ACCEPTED','REJECTED','EXPIRED')),
  expires_at DATETIME(3) NOT NULL,
  patient_id BIGINT UNSIGNED NULL,
  queue_ticket_id BIGINT UNSIGNED NULL,
  reviewed_by BIGINT UNSIGNED NULL,
  decision_hash CHAR(64) NULL,
  version INT NOT NULL DEFAULT 1 CHECK(version>0),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY registration_submission(branch_id,submission_key),
  UNIQUE KEY registration_ticket(branch_id,service_date,ticket_number),
  KEY registration_pending(tenant_id,branch_id,status,expires_at,id),
  KEY registration_expiry(status,expires_at),
  FOREIGN KEY(tenant_id,branch_id) REFERENCES branches(tenant_id,id),
  FOREIGN KEY(tenant_id,patient_id) REFERENCES patients(tenant_id,id),
  FOREIGN KEY(tenant_id,branch_id,queue_ticket_id) REFERENCES queue_tickets(tenant_id,branch_id,id),
  FOREIGN KEY(tenant_id,reviewed_by) REFERENCES users(tenant_id,id),
  CHECK((status='PENDING' AND payload IS NOT NULL) OR(status<>'PENDING' AND payload IS NULL)),
  CHECK(status<>'ACCEPTED' OR(patient_id IS NOT NULL AND queue_ticket_id IS NOT NULL AND reviewed_by IS NOT NULL))
) ENGINE=InnoDB;
